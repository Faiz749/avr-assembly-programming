.include "m32def.inc"
.org 0x00

MAIN:
    LDI R16,0xFF
	OUT DDRC,R16

RED:
     LDI R16,0b00000001
	 OUT PORTC,R16
	 RCALL DELAY

BLUE:
     LDI R16,0b00000010
	 OUT PORTC,R16
	 RCALL DELAY

YELLOW:
       LDI R16,0b00000100
	   OUT PORTC,R16
	   RCALL DELAY
	   RJMP RED

DELAY:
       LDI R17,0xFF
L_OUTER:
        LDI R18,0xFF
L_INNER:
        DEC R18
		BRNE L_INNER
	    DEC R17
		BRNE L_OUTER
		RET 