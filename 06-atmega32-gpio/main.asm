.include "m32def.inc"
.ORG 0x00
MAIN:
    LDI R16,0xFF
	OUT DDRD,R16
	CBI DDRB,0
	SBI PORTB,0
	CBI DDRB,1
	SBI PORTB,1

LOOP:
      SBIS PINB,0
	  RJMP PRESSED_1
	  RJMP CHECK_2

CHECK_2:
        SBIS PINB,1
		RJMP PRESSED_2
		RJMP NOT_PRESSED

PRESSED_1:
      LDI R16,0x0F
	  OUT PORTD,R16
	  RJMP LOOP

PRESSED_2: 
         LDI R16,0xF0
	     OUT PORTD,R16
	     RJMP LOOP


NOT_PRESSED: 
	        LDI R16,0x00
	        OUT PORTD,R16
	        RJMP LOOP
