.include "m32def.inc"
.org 0x00

MAIN:
    LDI R16,0xFF
	OUT DDRA,R16

RED: 
    LDI R16,0b00000001
	OUT PORTA,R16
    RCALL DELAY

BLUE:
    LDI R16,0b00000010
	OUT PORTA,R16
	RCALL DELAY

GREEN:
     LDI R16,0b00000100
	 OUT PORTA,R16
	 RCALL DELAY

YELLOW:
      LDI R16,0b00001000
	  OUT PORTA,R16
	  RCALL DELAY

RED2:
     LDI R17,0b00010000
	 OUT PORTA,R17
	 RCALL DELAY

BLUE2: 
      LDI R17,0b00100000
	  OUT PORTA,R17
	  RCALL DELAY

GREEN2:
      LDI R17,0b01000000
	  OUT PORTA,R17
	  RCALL DELAY

YELLOW2:
       LDI R17,0b10000000
	   OUT PORTA,R17
	   RCALL DELAY
	   RJMP RED

DELAY:
      PUSH R16
	  PUSH R17
	  LDI R16,0xFF
 L_1: LDI R17,0xFF
 L_2: DEC R17
      BRNE L_2
	  DEC R16
	  BRNE L_1
	  POP R17
	  POP R16
	  RET 

	  

